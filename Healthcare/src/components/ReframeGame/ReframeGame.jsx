// Client-side flood fill transparency processor
const floodFillAlpha = (imgData) => {
  const data = imgData.data;
  const width = imgData.width;
  const height = imgData.height;
  const visited = new Uint8Array(width * height);
  const queue = [];

  const getIndex = (x, y) => (y * width + x) * 4;

  const isWhite = (x, y) => {
    const idx = getIndex(x, y);
    return data[idx] > 220 && data[idx+1] > 220 && data[idx+2] > 220 && data[idx+3] > 0;
  };

  const add = (x, y) => {
    if (x >= 0 && x < width && y >= 0 && y < height) {
      const vIdx = y * width + x;
      if (!visited[vIdx] && isWhite(x, y)) {
        visited[vIdx] = 1;
        queue.push([x, y]);
      }
    }
  };

  // Seed from edges
  for (let x = 0; x < width; x++) {
    add(x, 0);
    add(x, height - 1);
  }
  for (let y = 0; y < height; y++) {
    add(0, y);
    add(width - 1, y);
  }

  while (queue.length > 0) {
    const [cx, cy] = queue.shift();
    const idx = getIndex(cx, cy);
    data[idx+3] = 0; // Transparent

    add(cx + 1, cy);
    add(cx - 1, cy);
    add(cx, cy + 1);
    add(cx, cy - 1);
  }
};

const makeImageTransparent = (imgUrl) => {
  return new Promise((resolve) => {
    const img = new Image();
    img.crossOrigin = "anonymous";
    img.onload = () => {
      try {
        const canvas = document.createElement('canvas');
        canvas.width = img.width;
        canvas.height = img.height;
        const ctx = canvas.getContext('2d');
        ctx.drawImage(img, 0, 0);
        const imgData = ctx.getImageData(0, 0, canvas.width, canvas.height);
        
        floodFillAlpha(imgData);
        
        // Also clear any remaining internal white pockets (R, G, B > 230)
        const data = imgData.data;
        for (let i = 0; i < data.length; i += 4) {
          if (data[i] > 230 && data[i+1] > 230 && data[i+2] > 230) {
            data[i+3] = 0; // Set alpha to 0
          }
        }
        
        ctx.putImageData(imgData, 0, 0);
        resolve(canvas.toDataURL());
      } catch (e) {
        console.error("Transparency filter error:", e);
        resolve(imgUrl);
      }
    };
    img.onerror = () => resolve(imgUrl);
    img.src = imgUrl;
  });
};

