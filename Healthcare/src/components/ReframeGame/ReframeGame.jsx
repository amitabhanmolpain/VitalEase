const drawSpeechBubble = (ctx, text, x, y) => {
  ctx.save();
  // Bubble body
  ctx.fillStyle = 'rgba(15, 23, 42, 0.95)'; // dark slate
  ctx.strokeStyle = '#2dd4bf'; // teal border
  ctx.lineWidth = 1.5;
  
  const w = 240;
  const h = 40;
  const rx = x;
  const ry = y;

  // Draw box
  ctx.beginPath();
  if (ctx.roundRect) {
    ctx.roundRect(rx, ry, w, h, 6);
  } else {
    ctx.rect(rx, ry, w, h);
  }
  ctx.fill();
  ctx.stroke();

  // Draw bubble pointer (pointing left towards the receptionist)
  ctx.fillStyle = 'rgba(15, 23, 42, 0.95)';
  ctx.beginPath();
  ctx.moveTo(rx, ry + 15);
  ctx.lineTo(rx - 8, ry + 20);
  ctx.lineTo(rx, ry + 25);
  ctx.closePath();
  ctx.fill();
  
  ctx.strokeStyle = '#2dd4bf';
  ctx.beginPath();
  ctx.moveTo(rx, ry + 15);
  ctx.lineTo(rx - 8, ry + 20);
  ctx.lineTo(rx, ry + 25);
  ctx.stroke();

  // Render text
  ctx.fillStyle = '#ffffff';
  ctx.font = '7px "Press Start 2P"';
  ctx.textAlign = 'center';
  ctx.textBaseline = 'middle';
  ctx.fillText(text, rx + w / 2, ry + h / 2);
  ctx.restore();
};

